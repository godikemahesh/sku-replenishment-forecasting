def write_docs(root: Path) -> None:
    docs = root / "docs"
    docs.mkdir(parents=True, exist_ok=True)
    rows = pd.DataFrame(dictionary_rows())
    rows.to_csv(docs / "data_dictionary.csv", index=False)
    pd.DataFrame(relationships()).to_csv(docs / "relationships.csv", index=False)
    (docs / "data_dictionary.md").write_text(dictionary_markdown(), encoding="utf-8")
    sql = root / "sql"
    sql.mkdir(parents=True, exist_ok=True)
    (sql / "schema.sql").write_text(ddl(), encoding="utf-8")


def dictionary_markdown() -> str:
    out = ["# Data dictionary", "", "Generated from `replenishment/schema.py`. Layers: **input** (what planners and models see), "
           "**output** (engine decisions), **ground_truth** (labels - never used as features).", ""]
    for layer in ["input", "output", "ground_truth"]:
        out.append(f"## Layer: {layer}\n")
        for t in TABLES.values():
            if t.layer != layer:
                continue
            out.append(f"### {t.entity} (`{t.name}`)\n\n{t.desc}\n\nPrimary key: `{', '.join(t.pk)}`"
                       + (f" | Natural key: `{', '.join(t.natural_key)}`" if t.natural_key else ""))
            if t.fks:
                out.append("Relationships: " + "; ".join(f"`{','.join(f.cols)}` -> `{f.ref_table}` ({f.cardinality})" for f in t.fks))
            out.append("\n| Field | Type | Req. | Allowed / unit | Rule | Description |\n|---|---|---|---|---|---|")
            for c in t.cols:
                allowed = " \\| ".join(c.allowed) if c.allowed else c.unit
                out.append(f"| `{c.name}` | {c.type} | {'Y' if c.required else 'N'} | {allowed} | {c.rule.replace('|', '/')} | {c.desc} |")
            out.append("")
    return "\n".join(out)


def _sql_value(v, typ):
    if v is None or (isinstance(v, float) and math.isnan(v)) or v is pd.NA:
        return "NULL"
    if typ == "boolean":
        return "1" if bool(v) else "0"
    if typ in ("integer",):
        return str(int(v))
    if typ == "decimal":
        return repr(float(v))
    return "'" + str(v).replace("'", "''") + "'"


def write_exports(root: Path) -> dict:
    """JSON per table and SQL INSERT seed for tables under the row limit; returns tables kept CSV-only."""
    csv_only = []
    with open(root / "sql" / "seed.sql", "w", encoding="utf-8", newline="\n") as seed:
        seed.write("-- Seed data generated by replenishment.export. Load schema.sql first.\nPRAGMA foreign_keys = ON;\nBEGIN;\n")
        for name in SQL_ORDER:
            path = table_path(root, name)
            if not path.exists():
                continue
            n = sum(1 for _ in open(path, encoding="utf-8")) - 1
            if n > JSON_SQL_ROW_LIMIT:
                csv_only.append({"table": name, "rows": n})
                continue
            df = read_table(root, name)
            jdir = root / "json" / TABLES[name].layer
            jdir.mkdir(parents=True, exist_ok=True)
            df.to_json(jdir / f"{name}.json", orient="records", indent=1, double_precision=6)
            cols = [c.name for c in TABLES[name].cols]
            types = [TABLES[name].col(c).type for c in cols]
            head = f"INSERT INTO {name} ({', '.join(cols)}) VALUES\n"
            vals = df[cols].astype(object).values
            for i in range(0, len(vals), 500):
                block = vals[i:i + 500]
                seed.write(head + ",\n".join("(" + ", ".join(_sql_value(v, t) for v, t in zip(row, types)) + ")" for row in block) + ";\n")
        seed.write("COMMIT;\n")
    return {"csv_only_tables": csv_only, "row_limit": JSON_SQL_ROW_LIMIT}


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_manifest(p: Profile, root: Path, command: str, exports: dict) -> dict:
    files = {}
    for f in sorted(root.rglob("*")):
        rel = f.relative_to(root).as_posix()
        if f.is_dir() or rel in ("manifest.json",) or rel.startswith("reports/reproducibility"):
            continue
        entry = {"bytes": f.stat().st_size, "sha256": sha256(f)}
        if f.suffix == ".csv":
            entry["rows"] = sum(1 for _ in open(f, encoding="utf-8")) - 1
        files[rel] = entry
    manifest = {
        "dataset": "SKU-location demand forecasting & replenishment (synthetic)",
        "generator_version": __version__,
        "profile": p.name, "seed": p.seed, "command": command,
        "scale": {"skus": p.n_skus, "stores": p.n_stores, "suppliers": p.n_suppliers, "history_days": p.n_days},
        "dates": {"history_start": str(p.history_start), "history_end": str(p.history_end),
                  "backtest_origin": str(p.backtest_origin), "holdout_days": p.holdout_days,
                  "forecast_month": p.forecast_month, "recommendation_date": str(p.recommendation_date)},
        "parameters": {"generator": GEN, "engine": {k: list(v) if isinstance(v, tuple) else v for k, v in ENGINE.items()},
                       "anomalies": ANOMALY, "review_period_days": p.review_period_days},
        "provenance": {"source": "100% synthetic - produced by this repository's generator from a fixed seed",
                       "external_data": "none", "personal_data": "none",
                       "reference_only": "Category seasonality and festival dates are hand-set to resemble Indian grocery retail; "
                                         "no third-party dataset was copied. Store, brand and supplier names are invented."},
        "exports": exports,
        "files": files,
    }
    (root / "manifest.json").write_text(json.dumps(manifest, indent=2, default=str), encoding="utf-8")
    return manifest
